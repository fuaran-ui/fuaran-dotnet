module Fuaran.UI.Tests.ChangeSetHandEditTests

// ============================================================================
//  Phase 2665 - the change-set command reports the hand edits a vocabulary
//  change cost.
//
//  `build/ChangeSet.fs` (linked into this suite) classes every file a change
//  touched, per roster host and in the corpus, as GENERATED (its header says
//  so, or the corpus's own data or the reference build lists it as a generator
//  output) or HAND. These tests pin that classification over a fixture
//  workspace built in a temporary directory: a kind-adding change across two
//  host checkouts and the corpus, with a hand-written file sitting beside a
//  generated one in each host, a bundled corpus snapshot, an authored corpus
//  family beside an emitted one, and a roster host whose checkout is absent.
// ============================================================================

open System
open System.Diagnostics
open System.IO
open System.Text.Json
open Expecto
open ChangeSet

let private write (root: string) (rel: string) (text: string) =
    let path = Path.Combine(root, rel)

    match Path.GetDirectoryName path with
    | null -> ()
    | parent -> Directory.CreateDirectory parent |> ignore

    File.WriteAllText(path, text)

let private git (cwd: string) (args: string list) =
    let psi =
        ProcessStartInfo(
            "git",
            [ "-c"
              "user.name=fixture"
              "-c"
              "user.email=fixture@example.invalid"
              "-c"
              "commit.gpgsign=false" ]
            @ args,
            WorkingDirectory = cwd,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false
        )

    use p =
        match Process.Start psi with
        | null -> failtest "could not start git"
        | p -> p

    let out = p.StandardOutput.ReadToEndAsync()
    let err = p.StandardError.ReadToEnd()
    p.WaitForExit()

    if p.ExitCode <> 0 then
        failtestf "git %s failed: %s" (String.Join(" ", args)) err

    out.Result |> ignore

/// A git repository at `root` holding `files`, committed as its base.
let private repo (root: string) (files: (string * string) list) =
    Directory.CreateDirectory root |> ignore
    git root [ "init"; "-q"; "-b"; "main" ]

    for rel, text in files do
        write root rel text

    git root [ "add"; "-A" ]
    git root [ "commit"; "-q"; "-m"; "base" ]

let private tempWorkspace () =
    let path =
        Path.Combine(Path.GetTempPath(), "fuaran-changeset-" + Guid.NewGuid().ToString("n"))

    Directory.CreateDirectory path |> ignore
    path

let private generatedFs =
    "// GENERATED by the codegen. Do not edit by hand: regenerate it.\nmodule G\n"

let private generatedPy =
    "\"\"\"GENERATED from idl.json - DO NOT EDIT BY HAND.\"\"\"\n"

/// The corpus's own data: a manifest with an emitted row family and an authored one, the
/// producer record, a self-enumerating directory with one emitted and one authored family, a
/// directory family, the declared copies placing the Python host's snapshot, and a roster of
/// three hosts, one of which has no checkout.
let private corpusFiles: (string * string) list =
    [ "manifest.json",
      """{ "version": 1, "schema": "schema.json", "idl": "idl.json",
  "fixtures": [
    { "id": "card", "kind": "node-round-trip", "inputFile": "nodes/card.json", "expectedFile": "nodes/card.json" },
    { "id": "bad", "kind": "hand-reject", "inputFile": "reject/bad.json" } ] }"""
      "corpus-producers.json",
      """{ "families": {
    "node-round-trip": { "producer": { "repository": "r", "emit": "e" } },
    "hand-reject": { "authored": "written with the specification" },
    "laws/emittedLaws": { "producer": { "repository": "r", "emit": "e" } },
    "laws/handLaws": { "authored": "written with the specification" },
    "diff": { "producer": { "repository": "r", "emit": "e" } } } }"""
      "laws/manifest.json",
      """{ "families": [ { "id": "emittedLaws", "file": "emitted.json" }, { "id": "handLaws", "file": "hand.json" } ] }"""
      "diff/manifest.json", """{ "version": 1 }"""
      "copies.json",
      """{ "kind": "copies", "records": [
    { "source": "manifest.json", "consumers": [ "Estate/fuaran-py/conformance/corpus/manifest.json" ] } ] }"""
      "conformance/roster.json",
      """{ "hosts": [
    { "id": "fuaran", "dir": "fuaran-dotnet", "role": "codec" },
    { "id": "fuaran-py", "dir": "fuaran-py", "role": "codec" },
    { "id": "fuaran-go", "dir": "fuaran-go", "role": "codec" } ] }"""
      "WIRE_FORMAT.md", "# spec\n"
      "schema.json", "{}"
      "idl.json", "{}" ]

let private classOf (listed: string -> string option) (path: string) = classify listed (fun _ -> None) path

let private isGenerated =
    function
    | Generated _ -> true
    | Hand -> false

[<Tests>]
let tests =
    testList
        "Phase 2665 - the change-set's hand-edit count"
        [ test "a generated header is recognised in each host's shape, and prose that mentions generation is not one" {
              let headers =
                  [ "// GENERATED by Fuaran.Core.Idl.Codegen — F# structural layer. Do not edit by hand."
                    "// <auto-generated>\n//     The C# veneer's enum seam."
                    "// Code generated by go run ./wire/idl/internal/gen from the corpus idl.json; DO NOT EDIT."
                    "// GENERATED by src/wire/idl_codegen.rs from the wire corpus's idl.json. DO NOT EDIT."
                    "// SPDX-License-Identifier: Apache-2.0\n// Copyright\n//\n// GENERATED from the wire corpus's idl.json — do not edit."
                    "\"\"\"GENERATED from ``idl.json`` — DO NOT EDIT BY HAND."
                    "<!--\n  FULLY GENERATED FILE (Phase 840) — the lenient variant."
                    "{\n  \"_\": \"GENERATED by docs/tools/authoring-pack.fsx. Do not hand-edit — run --write.\","
                    "{\n  \"kind\": \"index/v1\",\n  \"generatedBy\": \"docs/tools/authoring-pack.fsx --write\","
                    "// Vitest Snapshot v1, https://vitest.dev/guide/snapshot.html" ]

              for h in headers do
                  Expect.isTrue (generatedHeader h) (sprintf "a generated header: %s" h)

              let prose =
                  [ "# The generated layer\n\nThis document explains the generated layer."
                    "<!--\n  GENERATED-ADJACENT FILE. The prose here is authored; the examples are generated."
                    "// Do not edit this without review."
                    String.replicate 12 "// line\n"
                    + "// GENERATED — do not edit (too far down to be a header)" ]

              for p in prose do
                  Expect.isFalse (generatedHeader p) (sprintf "not a generated header: %s" p)
          }

          test "the corpus's own data names its generator outputs; an authored family and the specification are hand" {
              let ws = tempWorkspace ()

              try
                  let corpus = Path.Combine(ws, "wire-format-fixtures")

                  for rel, text in corpusFiles do
                      write corpus rel text

                  let listed = corpusOutputs corpus

                  for p in
                      [ "manifest.json"
                        "schema.json"
                        "idl.json"
                        "copies.json"
                        "nodes/card.json"
                        "laws/emitted.json"
                        "diff/goldens.json" ] do
                      Expect.isTrue (isGenerated (classOf listed p)) (sprintf "%s is a generator output" p)

                  for p in [ "reject/bad.json"; "laws/hand.json"; "laws/manifest.json"; "WIRE_FORMAT.md" ] do
                      Expect.equal (classOf listed p) Hand (sprintf "%s is hand-written" p)

                  let snapshot = snapshotOutputs corpus "fuaran-py"

                  Expect.isTrue
                      (isGenerated (classOf snapshot "conformance/corpus/nodes/card.json"))
                      "a file in the bundled snapshot is the sync step's output"

                  Expect.equal (classOf snapshot "conformance/host-capability-manifest.json") Hand "beside it, hand"
              finally
                  try
                      Directory.Delete(ws, true)
                  with _ ->
                      ()
          }

          test "a kind-adding change is counted per host, a hand file beside a generated one included" {
              let ws = tempWorkspace ()

              try
                  let corpus = Path.Combine(ws, "wire-format-fixtures")
                  let dotnet = Path.Combine(ws, "fuaran-dotnet")
                  let py = Path.Combine(ws, "fuaran-py")
                  repo corpus corpusFiles

                  repo
                      dotnet
                      [ "src/Idl/idl.json", "{ \"kinds\": [\"Card\"] }"
                        "src/UI/Generated.fs", generatedFs
                        "src/UI/Types.fs", "module T\n"
                        "src/UI/fuaran-reference.css", "/* sheet */" ]

                  repo
                      py
                      [ "src/schema/generated.py", generatedPy
                        "src/schema/types.py", "# types\n"
                        "conformance/corpus/manifest.json", "{}"
                        "src/renderer/fuaran-reference.css", "/* sheet */" ]

                  // The change: a new kind, hand-declared in each host beside its regenerated model.
                  write dotnet "src/Idl/idl.json" "{ \"kinds\": [\"Card\", \"Gauge\"] }"
                  write dotnet "src/UI/Generated.fs" (generatedFs + "type Gauge = Gauge\n")
                  write dotnet "src/UI/Types.fs" "module T\ntype GaugeSpec = { Value: float }\n"
                  write dotnet "src/UI/Render.fs" "module R\n" // untracked: a new hand file
                  write py "src/schema/generated.py" (generatedPy + "GAUGE = 'Gauge'\n")
                  write py "src/schema/types.py" "# types\nclass Gauge: ...\n"
                  write py "conformance/corpus/manifest.json" "{ \"v\": 2 }"
                  write py "conformance/corpus/nodes/gauge.json" "{}"
                  write py "src/renderer/fuaran-reference.css" "/* sheet + gauge */"
                  write corpus "nodes/gauge.json" "{}"

                  write
                      corpus
                      "manifest.json"
                      ((snd corpusFiles.Head)
                          .Replace(
                              "\"fixtures\": [",
                              "\"fixtures\": [ { \"id\": \"gauge\", \"kind\": \"node-round-trip\", \"inputFile\": \"nodes/gauge.json\" },"
                          ))

                  write corpus "WIRE_FORMAT.md" "# spec\n## Gauge\n"

                  let declared = [ "fuaran-py", "src/renderer/fuaran-reference.css" ]
                  let measured = measureAll ws corpus declared Map.empty

                  let countOf id =
                      match (measured |> List.find (fun m -> m.Host.Id = id)).Measured with
                      | Counted(_, files) ->
                          let g = files |> List.filter (snd >> isGenerated) |> List.map fst
                          let h = files |> List.filter (snd >> isGenerated >> not) |> List.map fst
                          g, h
                      | other -> failtestf "%s was not counted: %A" id other

                  let g, h = countOf "fuaran"
                  Expect.equal g [ "src/UI/Generated.fs" ] "fuaran: the regenerated model"
                  Expect.equal h [ "src/Idl/idl.json"; "src/UI/Render.fs"; "src/UI/Types.fs" ] "fuaran: the hand edits"

                  let g, h = countOf "fuaran-py"

                  Expect.equal
                      g
                      [ "conformance/corpus/manifest.json"
                        "conformance/corpus/nodes/gauge.json"
                        "src/renderer/fuaran-reference.css"
                        "src/schema/generated.py" ]
                      "fuaran-py: the snapshot, the declared copy, the generated model"

                  Expect.equal h [ "src/schema/types.py" ] "fuaran-py: the hand file beside the generated one"

                  let g, h = countOf "corpus"
                  Expect.equal g [ "manifest.json"; "nodes/gauge.json" ] "corpus: the emit's outputs"
                  Expect.equal h [ "WIRE_FORMAT.md" ] "corpus: the specification text"

                  Expect.equal
                      (measured |> List.find (fun m -> m.Host.Id = "fuaran-go")).Measured
                      Absent
                      "a roster host with no checkout is reported, never counted as zero"

                  // The record the run writes carries the same counts, and the hand files by name.
                  use doc = JsonDocument.Parse(handEditsJson "GREEN" measured)
                  let total = doc.RootElement.GetProperty "total"
                  Expect.equal (total.GetProperty("generated").GetInt32()) 7 "total generated"
                  Expect.equal (total.GetProperty("hand").GetInt32()) 5 "total hand"
                  Expect.equal (total.GetProperty("hostsUnmeasured").GetInt32()) 1 "the absent host"

                  // A recorded change is measured as a range: commit the work and ask for base..HEAD.
                  git dotnet [ "add"; "-A" ]
                  git dotnet [ "commit"; "-q"; "-m"; "gauge" ]

                  match measureHost (fun _ -> None) (rosterHosts ws corpus).Head (Some "HEAD~1..HEAD") with
                  | Counted(_, files) ->
                      Expect.equal
                          (files |> List.filter (snd >> isGenerated >> not) |> List.map fst)
                          [ "src/Idl/idl.json"; "src/UI/Render.fs"; "src/UI/Types.fs" ]
                          "the range counts the committed change the same way"
                  | other -> failtestf "the range was not counted: %A" other
              finally
                  try
                      Directory.Delete(ws, true)
                  with _ ->
                      ()
          }

          test "a dry run reports the counts and writes nothing; a run writes them" {
              let ws = tempWorkspace ()

              try
                  let out = Path.Combine(ws, "output", "change-set")

                  let host =
                      { Id = "fuaran"
                        DirName = "fuaran-dotnet"
                        Root = ws }

                  let measured =
                      [ { Host = host
                          Measured = Counted("HEAD", [ "a.fs", Hand ]) } ]

                  Expect.isNone (recordHandEdits true out "dry-run" measured) "a dry run returns no path"
                  Expect.isFalse (Directory.Exists out) "and creates nothing"

                  match recordHandEdits false out "GREEN" measured with
                  | Some path ->
                      Expect.equal (File.ReadAllText path) (handEditsJson "GREEN" measured + "\n") "the same record"
                  | None -> failtest "a run writes its record"
              finally
                  try
                      Directory.Delete(ws, true)
                  with _ ->
                      ()
          }

          test "--base takes host=rev items and refuses a malformed one" {
              let opts, rest =
                  splitArgs [| "ChangeSet"; "--base"; "fuaran=abc..def,corpus=HEAD~2"; "--dry-run" |]

              Expect.equal rest [| "ChangeSet" |] "the change-set's own flags are taken out"
              Expect.isTrue opts.DryRun "dry run"
              Expect.equal opts.Bases (Map.ofList [ "fuaran", "abc..def"; "corpus", "HEAD~2" ]) "the bases"

              Expect.throws
                  (fun () -> splitArgs [| "--base"; "fuaran" |] |> ignore)
                  "an item without a revision is refused"
          } ]
